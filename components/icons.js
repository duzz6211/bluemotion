function replaceEmojisWithIcons() {
    const emojiMap = {
        '📋': 'clipboard',
        '🏢': 'building',
        '🌊': 'waves',
        '📚': 'book',
        '🤝': 'handshake',
        '🌱': 'leaf',
        '👤': 'user',
        '✅': 'checkCircle',
        '✓': 'check',
        '👨‍🏫': 'graduationCap',
        '🎯': 'target',
        '🛡️': 'shield',
        '💪': 'dumbbell',
        '🧘': 'activity',
        '😊': 'smile',
        '👶': 'baby',
        '📞': 'phone',
        '📧': 'mail',
        '📍': 'mapPin',
        '🕐': 'clock',
        '🚗': 'car',
        '🚌': 'bus',
        '💬': 'messageCircle',
        '📈': 'trending',
        '⭐': 'star',
        '🎬': 'play',
        '📷': 'camera',
        '🔗': 'link'
    };

    // feature-icon 클래스를 가진 요소들의 이모티콘 변환
    document.querySelectorAll('.feature-icon, .info-icon').forEach(el => {
        const text = el.textContent.trim();
        if (emojiMap[text]) {
            el.innerHTML = icons[emojiMap[text]];
            el.querySelector('.icon')?.classList.add('icon-xl');
        }
    });
}

