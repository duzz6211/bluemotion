// 아이콘 렌더링 함수
function renderIcon(name, className = '') {
    if (icons[name]) {
        const wrapper = document.createElement('span');
        wrapper.innerHTML = icons[name];
        if (className) {
            wrapper.firstChild.classList.add(...className.split(' '));
        }
        return wrapper.innerHTML;
    }
    return '';
}

